"""LookML for the governed metrics, generated from ``metrics/metrics.yml``.

Looker measures are written from the same definitions as the SQL in
:mod:`support_bi.metrics`, so a dashboard tile and an ad hoc query cannot disagree about
what a metric means. One view is written per mart the metrics read:

- ``agg_support_daily``: a sum measure per additive component, and one ``number``
  measure per ratio metric that divides those sums, which stays correct at any grain.
- ``fct_cases``: percentile measures, which cannot be built from sums.
- ``fct_backlog_daily``: the open backlog, summed within a day and averaged over days.

The three marts have different grains, so each gets its own explore instead of a join
that would fan out. Customers come from the masked reporting view, and the model limits
rows by region (see :func:`model`). The files under ``looker/`` are committed; a test
fails when they drift from the spec.
"""

from __future__ import annotations

from collections.abc import Mapping
from pathlib import Path

from support_bi.metrics import COMPONENTS, DIMENSIONS, Kind, Metric

MODEL = "support_bi"
OUT_DIR = Path(__file__).resolve().parents[2] / "looker"
HEADER = (
    "# Generated by `support-bi lookml` from metrics/metrics.yml. Edit the YAML, not this file.\n"
)

_RELATION = {
    Kind.RATIO: "agg_support_daily",
    Kind.QUANTILE: "fct_cases",
    Kind.LEVEL: "fct_backlog_daily",
}
_VALUE_FORMAT = {"share": "0.0%", "cases": "#,##0", "minutes": "#,##0.0", "hours": "#,##0.0"}


def _text(value: str) -> str:
    """A LookML string literal."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _dimensions(kind: Kind) -> list[str]:
    date_column = DIMENSIONS["date"][kind.value]
    blocks = [
        f"  dimension_group: {date_column.removesuffix('_date')} {{\n"
        "    type: time\n"
        "    timeframes: [date, week, month, quarter, year]\n"
        "    convert_tz: no\n"
        "    datatype: date\n"
        f"    sql: ${{TABLE}}.{date_column} ;;\n"
        "  }"
    ]
    for name, columns in DIMENSIONS.items():
        if name in {"date", "month"} or kind.value not in columns:
            continue
        blocks.append(
            f"  dimension: {name} {{\n"
            "    type: string\n"
            f"    sql: ${{TABLE}}.{columns[kind.value]} ;;\n"
            "  }"
        )
    return blocks


def _measure(metric: Metric) -> str:
    lines = [f"  measure: {metric.name} {{"]
    if metric.kind is Kind.RATIO:
        value = f"${{{metric.numerator}_total}}"
        if metric.denominator:
            value = f"1.0 * {value} / NULLIF(${{{metric.denominator}_total}}, 0)"
        lines += ["    type: number", f"    sql: {value} ;;"]
    elif metric.kind is Kind.QUANTILE:
        assert metric.q is not None
        lines += [
            "    type: percentile",
            f"    percentile: {round(metric.q * 100)}",
            f"    sql: ${{TABLE}}.{metric.column} ;;",
        ]
    else:
        # One row per product and priority per day: sum within the day, average over days,
        # the same way metrics.sql does. A plain average of rows would understate it.
        days = f"COUNT(DISTINCT ${{TABLE}}.{DIMENSIONS['date'][Kind.LEVEL.value]})"
        value = f"1.0 * SUM(${{TABLE}}.{metric.column}) / NULLIF({days}, 0)"
        lines += ["    type: number", f"    sql: {value} ;;"]
    lines += [
        f"    label: {_text(metric.label)}",
        f"    description: {_text(metric.description)}",
        f"    group_label: {_text(metric.owner)}",
    ]
    if metric.unit in _VALUE_FORMAT:
        lines.append(f"    value_format: {_text(_VALUE_FORMAT[metric.unit])}")
    lines.append("  }")
    return "\n".join(lines)


def _components() -> list[str]:
    return [
        f"  measure: {name}_total {{\n"
        "    type: sum\n"
        "    hidden: yes\n"
        f"    sql: ${{TABLE}}.{name} ;;\n"
        "  }"
        for name in sorted(COMPONENTS)
    ]


def view(kind: Kind, metrics: Mapping[str, Metric], schema: str = "marts") -> str:
    """The LookML view over the mart that metrics of ``kind`` read."""
    relation = _RELATION[kind]
    blocks = _dimensions(kind)
    if kind is Kind.QUANTILE:
        # The case fact joins to customers; the key itself is not something to chart.
        blocks.append(
            "  dimension: customer_key {\n"
            "    hidden: yes\n"
            "    type: string\n"
            "    sql: ${TABLE}.customer_key ;;\n"
            "  }"
        )
    if kind is Kind.RATIO:
        blocks += _components()
    blocks += [_measure(m) for m in metrics.values() if m.kind is kind]
    body = "\n\n".join(blocks)
    return (
        f"{HEADER}\nview: {relation} {{\n  sql_table_name: {schema}.{relation} ;;\n\n{body}\n}}\n"
    )


REGION_ATTRIBUTE = "support_region"
SCOPE_ATTRIBUTE = "support_scope"
GLOBAL_SCOPE = "global"
CUSTOMER_DIMENSIONS = ("customer_label", "email_domain", "region", "tier", "tier_name")


def customers_view(schema: str = "reporting") -> str:
    """Customers as dashboards may see them: the masked dbt view, never dim_customer."""
    blocks = [
        "  dimension: customer_key {\n"
        "    primary_key: yes\n"
        "    hidden: yes\n"
        "    type: string\n"
        "    sql: ${TABLE}.customer_key ;;\n"
        "  }"
    ]
    blocks += [
        f"  dimension: {name} {{\n    type: string\n    sql: ${{TABLE}}.{name} ;;\n  }}"
        for name in CUSTOMER_DIMENSIONS
    ]
    body = "\n\n".join(blocks)
    table = f"  sql_table_name: {schema}.rpt_customers ;;"
    return f"{HEADER}\nview: customers {{\n{table}\n\n{body}\n}}\n"


def model(connection: str = "support_warehouse") -> str:
    """The model: who may open which explore, and which rows they get.

    Row-level access is by region, using two Looker user attributes:

    - ``support_region`` filters the case explore to the user's customers. It holds a
      region (``EMEA``), a list (``NA, LATAM``) or ``%`` for every region.
    - ``support_scope`` set to ``global`` opens the two aggregate explores. Their rows
      carry no customer and cannot be filtered by region, so a regional user gets their
      numbers from the case explore instead.

    A filter value cannot double as the grant: ``%`` is a pattern in a filter but just
    a string in ``allowed_values``, which is why there are two attributes.
    """
    grant = (
        "access_grant: all_regions {\n"
        f"  user_attribute: {SCOPE_ATTRIBUTE}\n"
        f"  allowed_values: [{_text(GLOBAL_SCOPE)}]\n"
        "}"
    )
    cases = (
        "explore: fct_cases {\n"
        f"  label: {_text('Cases')}\n"
        "  access_filter: {\n"
        "    field: customers.region\n"
        f"    user_attribute: {REGION_ATTRIBUTE}\n"
        "  }\n"
        "  join: customers {\n"
        "    type: inner\n"
        "    relationship: many_to_one\n"
        "    sql_on: ${fct_cases.customer_key} = ${customers.customer_key} ;;\n"
        "  }\n"
        "}"
    )
    aggregates = "\n\n".join(
        f"explore: {relation} {{\n  label: {_text(label)}\n"
        "  required_access_grants: [all_regions]\n}"
        for relation, label in [
            ("agg_support_daily", "Support metrics (daily)"),
            ("fct_backlog_daily", "Backlog"),
        ]
    )
    return (
        f"{HEADER}\nconnection: {_text(connection)}\n\n"
        'include: "/views/*.view.lkml"\n\n'
        f"{grant}\n\n{cases}\n\n{aggregates}\n"
    )


def render(metrics: Mapping[str, Metric]) -> dict[str, str]:
    """Every generated file, keyed by its path under ``looker/``."""
    files = {f"views/{_RELATION[kind]}.view.lkml": view(kind, metrics) for kind in Kind}
    files["views/customers.view.lkml"] = customers_view()
    files[f"{MODEL}.model.lkml"] = model()
    return files


def write(metrics: Mapping[str, Metric], out: Path = OUT_DIR) -> list[Path]:
    paths = []
    for name, content in render(metrics).items():
        path = out / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        paths.append(path)
    return paths
